# ---------------------------------------------------------------------------
# 11. Invalid JSON produces explicit error
# ---------------------------------------------------------------------------

def test_invalid_json_produces_explicit_error(tmp_path: Path):
    """Verify that corrupted JSON in a report artifact produces a clear 500 error."""
    # Create a corrupted report in temporary directory
    bad_file = tmp_path / "reports" / "latest_release_report.json"
    bad_file.parent.mkdir(parents=True, exist_ok=True)
    bad_file.write_text("{corrupted json content: true", encoding="utf-8")

    app = create_app(repo_root=tmp_path)
    app.config["TESTING"] = True
    test_client = app.test_client()

    res = test_client.get("/api/report/synthesis")
    assert res.status_code == 500
    data = res.get_json()
    assert data["status"] == "INVALID_JSON"
    assert "Invalid JSON in report" in data["error"]


