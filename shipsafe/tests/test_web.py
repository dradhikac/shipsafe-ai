# 5. Findings endpoint returns synthesized findings
# ---------------------------------------------------------------------------

def test_findings_endpoint_returns_synthesized_findings(client):
    """Verify GET /api/findings returns findings and supports severity filtering."""
    res = client.get("/api/findings")
    assert res.status_code == 200
    data = res.get_json()
    assert data["total_available"] in (0, 22)
    assert data["filtered_count"] in (0, 22)

    # Filter for critical findings only
    res_crit = client.get("/api/findings?severity=CRITICAL")
    assert res_crit.status_code == 200
    data_crit = res_crit.get_json()
    if data["total_available"] == 22:
        assert data_crit["filtered_count"] == 1
        assert data_crit["findings"][0]["severity"] == "CRITICAL"
    else:
        assert data_crit["filtered_count"] == 0

    # Filter for high findings only
    res_high = client.get("/api/findings?severity=HIGH")
    assert res_high.status_code == 200
    data_high = res_high.get_json()
    if data["total_available"] == 22:
        assert data_high["filtered_count"] == 19
    else:
        assert data_high["filtered_count"] == 0


